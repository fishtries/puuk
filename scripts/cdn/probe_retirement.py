#!/usr/bin/env python3
"""Retire only the generated fixture and prove purge before capability expiry.

Run after expose and the closed pilot/rollback probe. The backend's existing
outbox submits the purge; this script does not call the provider directly.
"""
import base64
import hashlib
import http.client
import json
import os
from pathlib import Path
import sqlite3
import subprocess
import time

STAGE = Path('/home/fish/puuk-cdn-setup')
PYTHON = '/home/fish/apps/puuk/puuk/brain/venv/bin/python'


def fixture(mode):
    result = subprocess.run([PYTHON, str(STAGE / 'acceptance-fixture.py'), mode], timeout=45)
    if result.returncode:
        raise ValueError('fixture_action_failed')


def main():
    if os.geteuid() != 0:
        raise ValueError('root_required')
    pid = subprocess.run(['systemctl', 'show', 'puuk-brain', '--property=MainPID', '--value'],
                         capture_output=True, text=True, check=True, timeout=5).stdout.strip()
    env = dict(os.fsdecode(s).split('=', 1) for s in Path('/proc/' + pid + '/environ').read_bytes().split(b'\0') if b'=' in s)
    if any(env.get(k) != v for k, v in {'CDN_DELIVERY_ENABLED': 'false', 'CDN_ORIGIN_ENABLED': 'true', 'CDN_PURGE_ENABLED': 'true'}.items()):
        raise ValueError('closed_flags_required')
    state = json.loads((STAGE / 'acceptance-fixture.json').read_bytes())
    if state['phase'] != 'exposed' or state['expires_at'] < time.time() + 300:
        raise ValueError('refresh_fixture_exposure_first')
    tid = state['track_id']
    path = '/cdn/audio/' + tid + '/' + state['sha256']
    expiry = int(state['expires_at'])
    token = base64.urlsafe_b64encode(hashlib.md5((str(expiry) + path + ' ' + env['CDN_SIGNING_SECRET']).encode(), usedforsecurity=False).digest()).decode().rstrip('=')
    target = path + '?md5=' + token + '&expires=' + str(expiry)
    expected = (STAGE / 'acceptance-silence.mp3').read_bytes()
    c = http.client.HTTPSConnection('media.puuk.fun', timeout=5)
    def get():
        c.request('GET', target)
        r = c.getresponse()
        raw = r.read(81128)
        return r.status, raw, r.getheader('Cache-Status', ''), r.getheader('cache-host', '')
    try:
        second = None
        for attempt in range(6):
            second = get()
            if second[0] != 200 or second[1] != expected:
                raise ValueError('fixture_bytes_not_proven_status_' + str(second[0]))
            if 'HIT' in second[2].upper():
                break
            time.sleep(1)
        else:
            raise ValueError('warm_fixture_not_proven_after_six_gets')
        node = second[3]
        print('PRE_RETIREMENT: PASS; exact generated bytes warm on maintained edge connection.', flush=True)
        fixture('retire')
        db = sqlite3.connect('file:' + env.get('PUUK_DB_PATH', '/home/fish/apps/puuk/puuk/brain/puuk.db') + '?mode=ro', uri=True, timeout=1)
        try:
            deadline = time.monotonic() + 90
            while True:
                jobs = db.execute('SELECT state FROM cdn_purge_outbox WHERE track_id=?', (tid,)).fetchall()
                if jobs and all(row[0] == 'succeeded' for row in jobs):
                    break
                if time.monotonic() >= deadline:
                    raise ValueError('purge_not_confirmed_in_probe_budget')
                # Keep the same edge TLS connection alive, bounded and fixture-only.
                get()
                time.sleep(3)
        finally:
            db.close()
        deadline = time.monotonic() + 45
        while True:
            result = get()
            if time.time() >= expiry or result[3] != node:
                raise ValueError('expiry_or_node_changed_no_purge_proof')
            if result[0] == 404:
                break
            if time.monotonic() >= deadline:
                raise ValueError('edge_still_serving_retired_fixture')
            time.sleep(3)
        print('RETIREMENT_PURGE: PASS; durable outbox succeeded; same warm URL/node now404 before expiry.', flush=True)
    finally:
        c.close()
    fixture('cleanup')


if __name__ == '__main__':
    try:
        main()
    except Exception as exc:
        print('Retirement probe stopped:', type(exc).__name__, str(exc) if isinstance(exc, ValueError) else '')
        raise SystemExit(1)
